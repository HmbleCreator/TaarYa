"""
Generate LaTeX tables, macros, and synchronized text numbers directly from evaluation results.

Source files:
  - eval/benchmark_results.json
  - eval/real_benchmarks_summary.json
  - eval/ablation_table.tex

Outputs:
  - eval/paper_macros.tex (authoritative number macros)
  - eval/tables_generated.tex (compilable, clean LaTeX tables)
  - Synchronizes Paper/taarya_paper.tex and taarya_paper.tex to eliminate hand-copying discrepancies.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVAL_DIR = ROOT / "eval"


def load_data():
    bench_file = EVAL_DIR / "benchmark_results.json"
    with open(bench_file, "r", encoding="utf-8") as f:
        bench = json.load(f)

    real_file = EVAL_DIR / "real_benchmarks_summary.json"
    with open(real_file, "r", encoding="utf-8") as f:
        real = json.load(f)

    return bench, real


